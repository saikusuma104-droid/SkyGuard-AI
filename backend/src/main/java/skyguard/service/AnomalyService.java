package skyguard.service;

import org.springframework.stereotype.Service;

import skyguard.client.MLServiceClient;
import skyguard.dto.AnomalyResponse;
import skyguard.dto.WeatherRequest;
import skyguard.entity.WeatherReading;
import skyguard.repository.WeatherReadingRepository;

import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;

@Service
public class AnomalyService {

    private final MLServiceClient mlServiceClient;
    private final WeatherReadingRepository weatherReadingRepository;

    public AnomalyService(
            MLServiceClient mlServiceClient,
            WeatherReadingRepository weatherReadingRepository) {

        this.mlServiceClient = mlServiceClient;
        this.weatherReadingRepository = weatherReadingRepository;
    }

    public Object getLiveAWSData() {
        return mlServiceClient.getLiveAWSData();
    }

    public AnomalyResponse checkAnomaly(WeatherRequest request) {
        // 1. Send request to Python FastAPI ML service
        AnomalyResponse response = mlServiceClient.predict(request);

        // 2. Save real result to PostgreSQL database
        if (response != null) {
            try {
                WeatherReading reading = new WeatherReading();
                reading.setStationId(request.getStationId() != null ? request.getStationId() : response.getStation_id());
                
                // For DEMO mode, timestamp must be generated by backend using current time
                boolean isDemo = "DEMO".equalsIgnoreCase(request.getDataSource());
                if (isDemo || request.getTimestamp() == null || request.getTimestamp().trim().isEmpty()) {
                    reading.setTimestamp(LocalDateTime.now());
                } else {
                    reading.setTimestamp(parseTimestamp(request.getTimestamp()));
                }

                reading.setTemperature(request.getTemperature());
                reading.setDewPointTemperature(request.getDewPointTemperature());
                reading.setWindDirection(request.getWindDirection());
                reading.setWindSpeed(request.getWindSpeed());
                reading.setRelativeHumidity(request.getRelativeHumidity());
                reading.setVisibility(request.getVisibility());
                reading.setStationLevelPressure(request.getStationLevelPressure());
                reading.setSeaLevelPressure(request.getSeaLevelPressure());

                reading.setAnomaly(response.isAnomaly());
                reading.setAnomalyScore(response.getAnomaly_score());
                reading.setStatus(response.getStatus() != null ? response.getStatus() : (response.isAnomaly() ? "ANOMALY" : "NORMAL"));
                reading.setSeverity(response.getSeverity() != null ? response.getSeverity() : (response.isAnomaly() ? "CRITICAL" : "NORMAL"));
                reading.setReason(response.getReason());
                reading.setDataSource(isDemo ? "DEMO" : (request.getDataSource() != null ? request.getDataSource() : "LIVE"));

                weatherReadingRepository.save(reading);
            } catch (Exception e) {
                System.err.println("Error saving weather reading to database: " + e.getMessage());
                throw new org.springframework.web.server.ResponseStatusException(
                        org.springframework.http.HttpStatus.INTERNAL_SERVER_ERROR,
                        "Unable to save the demo observation.",
                        e
                );
            }
        }

        // 3. Return original response
        return response;
    }

    private LocalDateTime parseTimestamp(String timestampStr) {
        if (timestampStr == null || timestampStr.trim().isEmpty()) {
            return LocalDateTime.now();
        }
        String ts = timestampStr.trim();
        try {
            if (ts.contains("T")) {
                return LocalDateTime.parse(ts);
            } else if (ts.contains(" ")) {
                return LocalDateTime.parse(ts, DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss"));
            } else {
                return LocalDateTime.parse(ts, DateTimeFormatter.ISO_LOCAL_DATE_TIME);
            }
        } catch (Exception e) {
            return LocalDateTime.now();
        }
    }
}
