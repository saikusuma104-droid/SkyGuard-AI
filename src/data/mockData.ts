const generateHistory = (baseTemp: number, basePress: number, baseHum: number, isAnomaly: boolean = false, spikeParam?: 'temp' | 'press' | 'hum'): Array<{
  time: string;
  observedTemp: number;
  expectedTemp: number;
  observedPressure: number;
  expectedPressure: number;
  observedHumidity: number;
  expectedHumidity: number;
  isAnomaly?: boolean;
}> => {
  const times = ['06:00', '07:00', '08:00', '09:00', '09:30', '10:00', '10:15', '10:30'];
  return times.map((t, idx) => {
    const isLatest = idx >= times.length - 2;
    let obsT = baseTemp + (idx * 0.8 - 2.5) + (Math.sin(idx) * 0.4);
    let expT = baseTemp + (idx * 0.8 - 2.5);
    let obsP = basePress - (idx * 0.3) + (Math.cos(idx) * 0.2);
    let expP = basePress - (idx * 0.3);
    let obsH = baseHum - (idx * 1.5) + (Math.sin(idx * 2) * 1.2);
    let expH = baseHum - (idx * 1.5);

    let anomalyFlag = false;

    if (isAnomaly && isLatest) {
      anomalyFlag = true;
      if (spikeParam === 'temp') {
        obsT = 55.2;
      } else if (spikeParam === 'press') {
        obsP = 948.2;
      } else if (spikeParam === 'hum') {
        obsH = 96.4;
      }
    }

    return {
      time: t,
      observedTemp: Number(obsT.toFixed(1)),
      expectedTemp: Number(expT.toFixed(1)),
      observedPressure: Number(obsP.toFixed(1)),
      expectedPressure: Number(expP.toFixed(1)),
      observedHumidity: Number(Math.min(100, Math.max(10, obsH)).toFixed(0)),
      expectedHumidity: Number(Math.min(100, Math.max(10, expH)).toFixed(0)),
      isAnomaly: anomalyFlag,
    };
  });
};

